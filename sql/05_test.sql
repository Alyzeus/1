SELECT group_no, actual_people FROM tour_group WHERE group_no = 'TG260702'; -- 应为 3

-- ---------------------------------------------------------------
-- 用例004：入团超员【预期报错：该旅游团已满（上限50人），禁止入团】
-- 先临时把 TG260702 人数置为 50 模拟满团，测试后恢复
-- ---------------------------------------------------------------
UPDATE tour_group SET actual_people = 50 WHERE group_no = 'TG260702';
INSERT INTO group_member (group_no, tourist_no) VALUES ('TG260702', 'T0000001'); -- 触发器拦截
UPDATE tour_group SET actual_people = 3 WHERE group_no = 'TG260702';             -- 恢复

-- ---------------------------------------------------------------
-- 用例005：成团校验
-- ---------------------------------------------------------------
